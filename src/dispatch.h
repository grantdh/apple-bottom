// =============================================================================
// dispatch.h — GPU-or-Accelerate routing of BLAS-ABI calls (internal)
// =============================================================================
//
// Where a raw-pointer BLAS-ABI call runs. GEMM (dgemm_, zgemm_, ab_dgemm_,
// ab_zgemm_, ab_dgemm_blas, ab_zgemm_blas) is routed here entirely; BLAS-2
// (dgemv_, zgemv_, zhemv_, ab_*gemv_blas, ab_zhemv_blas) stays on Accelerate
// below AB_BLAS2_MIN_DIM, then shares steps 1-3 through
// ab_dispatch_mode_route() and has its own auto rule (blas2_abi.c).
// The native ABMatrix and device APIs never come here. Calls with invalid
// arguments or alpha == 0 run on Accelerate before routing (blas_wrapper.c,
// blas2_abi.c).
//
// Precedence, per call; the settings are read once per process:
//   1. AB_MODE=cpu: Accelerate.
//   2. M, N or K <= AB_MIN_GPU_DIM (default 32): Accelerate, in every mode.
//   3. AB_MODE=gpu: the GPU.
//   4. AB_MODE=auto (the default; any value other than cpu/gpu) with a FLOP
//      override: the GPU iff the call's FLOPs (2·M·N·K real, 8·M·N·K
//      complex) reach AB_CROSSOVER_FLOPS_REAL (DGEMM) or AB_CROSSOVER_FLOPS
//      (ZGEMM, and DGEMM when AB_CROSSOVER_FLOPS_REAL is unset).
//   5. AB_MODE=auto: the dispatch table: the file AB_DISPATCH_TABLE names, or
//      else the built-in table calibrated on this machine's chip
//      (dispatch_table.h: one table per calibrated chip, generated by
//      scripts/ingest_calibration.py from benchmarks/calibration/<chip>/).
//      The GPU iff a row of the call's routine and transposition class has
//      min_M <= M, min_N <= N and min_K <= K. A chip without a built-in
//      table has no rows: every auto call runs on Accelerate.
//
// The chip is machdep.cpu.brand_string ("Apple M2 Max", the same string as
// the Metal device name) and the GPU core count is the IORegistry's
// gpu-core-count; AB_CHIP and AB_GPU_CORES override them, for tests and to
// borrow another chip's table deliberately. A table matches a chip when the
// names are equal and its core count is the machine's, or it was calibrated
// with no core count (0: it applies to every variant of the chip), or the
// machine's count is unknown and the chip has one table. A sibling with a
// different core count (an M2 Max with 30 instead of 38 cores) therefore
// gets no table, not a wrong one.
//
// Table file format (what `make calibrate` writes), one row per line, '#'
// starts a comment:
//   <dgemm|zgemm> <transA> <transB> <min_M> <min_N> <min_K>
// TRANS is a class: 'N', or 'T' for both 'T' and 'C' ('C' is accepted as
// 'T'). A file without rows keeps every auto call on Accelerate. A file that
// cannot be read or parsed is reported on stderr and the built-in table used.
// Three comment lines carry the calibration's identity; the loader reads
// back chip and gpu_cores (cpu_matrix is recorded for the filed table and
// the generated header by scripts/ingest_calibration.py):
//   # chip: Apple M2 Max
//   # gpu_cores: 38
//   # cpu_matrix: AMX
// A file whose chip or core count differs from this machine's is used, with
// a note on stderr: the user asked for it.
//
// AB_SPLIT=1 (opt-in; unset, empty or starting with '0' is off) adds a step
// between 2 and 3: a dgemm_/zgemm_ call that matches a row of the chip's
// split table is cut in two, one part on Accelerate and one on the GPU
// (blas_wrapper.c, split_slice.h). Under auto, calls no row covers follow
// the table; under gpu they go to the GPU whole. The split table is the
// built-in one for this chip (split_table.h, generated by
// scripts/ingest_split.py from benchmarks/split/tables/<chip>/), or the file
// AB_SPLIT_TABLE names (a path of at most AB_SPLIT_PATH_MAX, 154 bytes),
// which replaces it. A chip without one splits nothing (one note on stderr).
// Split table format, '#' starts a comment:
//   <dgemm|zgemm> <ta> <tb> <axis> [m=lo:hi] [n=lo:hi] [k=lo:hi] [mn=lo:hi]
//                 [ratio=r] [gf=g] [scalars=u|z|a] f=<share>
// Fields are separated by spaces or tabs, and a line may be of any length.
// m, n and k are ASCII digits; the other values ASCII numbers (digits, a
// point, an exponent, no sign but '+'), finite, and 0 or at least DBL_MIN.
// TRANS is exact ('N', 'T' or 'C', case-folded; a DGEMM 'C' is 'T'); axis
// 'N' cuts C's columns, 'M' its rows, 'K' the sum. Ranges are inclusive and
// either end may be left out (hi 0 or absent: no limit); mn bounds M*N,
// ratio bounds max(M,N,K)/min(M,N,K), gf the call's GFLOP (2MNK, complex
// 8MNK). scalars: 'u' alpha 1 and beta 0 or 1, 'z' alpha 1 and beta 0, 'a'
// (or absent) any finite. f is the GPU's share; 0 attributes the calls to the
// row in the reports and splits none. The first row that matches wins. Two
// limits hold whatever a table says: the N and M axes need K <= M, the K
// axis K >= 7 max(M, N). Header keys: chip, gpu_cores, cpu_matrix, library
// (the commit the shares were measured on), date, method.
// =============================================================================
#ifndef AB_DISPATCH_H
#define AB_DISPATCH_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

typedef enum { AB_DISPATCH_AUTO, AB_DISPATCH_CPU, AB_DISPATCH_GPU } ab_dispatch_mode_t;

// A row sends calls of `routine` ('d' DGEMM, 'z' ZGEMM) whose TRANS flags
// fall in classes ta, tb ('N' or 'T') to the GPU when M >= m, N >= n, K >= k.
// A table's rows end with a row whose routine is 0.
typedef struct {
    char routine, ta, tb;
    int m, n, k;
} ab_dispatch_row_t;

// One calibrated chip (dispatch_table.h). The built-in set ends with an
// entry whose chip is NULL.
typedef struct {
    const char *chip;               // machdep.cpu.brand_string, e.g. "Apple M2 Max"
    int gpu_cores;                  // IORegistry gpu-core-count; 0: every variant of the chip
    const char *cpu_matrix;         // "AMX" or "SME": what Accelerate ran on when calibrated
    const char *data;               // its calibrate_summary.csv, relative to the source root
    const ab_dispatch_row_t *rows;  // ends with a row whose routine is 0
} ab_dispatch_table_t;

#define AB_DISPATCH_MAX_ROWS        64
#define AB_DISPATCH_DEFAULT_MIN_DIM 32
#define AB_DISPATCH_DEFAULT_BLAS2_MIN_DIM 256
#define AB_DISPATCH_CHIP_LEN        64
#define AB_DISPATCH_LABEL_LEN       160
#define AB_SPLIT_MAX_ROWS           32
// The longest AB_SPLIT_TABLE path, so that "file:<path>" fits the split_table
// label whole (154 bytes); a longer one is refused, with a note.
#define AB_SPLIT_PATH_MAX           (AB_DISPATCH_LABEL_LEN - sizeof "file:")

// One row of a split table (AB_SPLIT, above). A table's rows end with a row
// whose routine is 0.
typedef struct {
    char routine, ta, tb;          // exact TRANS, upper-cased; a DGEMM 'C' is 'T'
    char axis;                     // 'N', 'M' or 'K'
    int min_m, max_m, min_n, max_n, min_k, max_k;   // max 0: no limit
    double min_mn, max_mn;         // M*N window (max 0: no limit); class tables only
    double ratio;                  // 0, or max(M,N,K) <= ratio*min(M,N,K)
    double min_gf;                 // GFLOP of the whole call
    char scalars;                  // 'u' alpha 1, beta 0 or 1; 'z' alpha 1, beta 0; 'a' any finite
    double share;                  // the GPU's part; 0: attribute the calls, do not split
} ab_split_row_t;

// One chip's built-in split table (split_table.h); the set ends with an
// entry whose chip is NULL. chip and gpu_cores come first, as in
// ab_dispatch_table_t: the two are chosen by the same rule.
typedef struct {
    const char *chip;
    int gpu_cores;
    const char *cpu_matrix;
    const char *library;            // the commit the shares were measured on
    const char *data;               // its split_evidence.csv, relative to the source root
    const ab_split_row_t *rows;     // ends with a row whose routine is 0
} ab_split_table_t;

// Where one call is cut: the first matching row, its axis, the length L of
// C's columns (N), rows (M) or the sum (K), and g, the GPU's part of L (the
// tail; 0: not split).
typedef struct { int row; char axis; int L, g; } ab_split_plan_t;

typedef struct {
    ab_dispatch_mode_t mode;                // AB_MODE
    int min_dim;                            // AB_MIN_GPU_DIM
    int blas2_min_dim;                      // AB_BLAS2_MIN_DIM
    uint64_t crossover_flops;               // AB_CROSSOVER_FLOPS, 0 = unset
    uint64_t crossover_flops_real;          // AB_CROSSOVER_FLOPS_REAL, 0 = unset
    char chip[AB_DISPATCH_CHIP_LEN];        // this machine's chip (AB_CHIP or sysctl); "" if unknown
    int gpu_cores;                          // this machine's GPU cores (AB_GPU_CORES or IORegistry); 0 if unknown
    char table_chip[AB_DISPATCH_CHIP_LEN];  // the chip the rows were calibrated on ("" if none / unstated)
    int table_gpu_cores;                    // and its core count (0 if unstated)
    char table[AB_DISPATCH_LABEL_LEN];      // where the rows came from, for AB_REPORT and AB_TRACE:
                                            // "builtin:<slug>", "file:<path>", "none:uncalibrated-chip"
                                            // or "none:unknown-chip"
    int nrows;
    ab_dispatch_row_t rows[AB_DISPATCH_MAX_ROWS];
    bool split_on;                                // AB_SPLIT
    char split_table[AB_DISPATCH_LABEL_LEN];      // ab_split_source(): "off", "builtin:<slug>@<library>",
                                                  // "file:<path>", "none:uncalibrated-chip" or
                                                  // "none:unknown-chip"
    char split_table_chip[AB_DISPATCH_CHIP_LEN];  // the chip the split rows were measured on
    int split_table_gpu_cores;                    // and its core count (0 if unstated)
    int split_nrows;                              // 0 unless split_on
    ab_split_row_t split_rows[AB_SPLIT_MAX_ROWS];
} ab_dispatch_config_t;

// True if `row` covers a call: same routine and TRANS classes, and M, N, K
// at least the row's minimums.
bool ab_dispatch_row_covers(const ab_dispatch_row_t *row, char routine,
                            char transA, char transB, int M, int N, int K);

// Steps 1-3 above for a call whose smallest dimension is min_dim: 0 for
// Accelerate, 1 for the GPU, -1 if the mode leaves it to the auto rule.
int ab_dispatch_mode_route(const ab_dispatch_config_t *c, int min_dim);

// The routing decision for one call with valid arguments under config c:
// true for the GPU. Pure: reads no environment and touches no GPU.
bool ab_dispatch_gpu(const ab_dispatch_config_t *c, char routine,
                     char transA, char transB, int M, int N, int K);

// Parses one table line into *row: 1 for a row, 0 for a blank or comment
// line, -1 if malformed.
int ab_dispatch_parse_row(const char *line, ab_dispatch_row_t *row);

// Parses one "# key: value" header line of a table file: 1 and *key, *value
// (trimmed, within the caller's buffers) for a header line, 0 otherwise.
int ab_dispatch_parse_header(const char *line, char *key, size_t key_len,
                             char *value, size_t value_len);

// Replaces c's rows with those of the table file at path, and c's table_chip
// and table_gpu_cores with the file's "# chip:" and "# gpu_cores:" headers
// (cleared when absent). On failure c is unchanged and err says why (with
// the line number for a malformed line).
bool ab_dispatch_load_table(ab_dispatch_config_t *c, const char *path,
                            char *err, size_t err_len);

// The table of `tables` (ending with a NULL chip) for a chip and GPU core
// count, by the matching rule above; NULL if none. Pure.
const ab_dispatch_table_t *ab_dispatch_select_table(const ab_dispatch_table_t *tables,
                                                    const char *chip, int gpu_cores);

// ab_dispatch_select_table() over the built-in set (dispatch_table.h).
const ab_dispatch_table_t *ab_dispatch_builtin_table(const char *chip, int gpu_cores);

// This machine's chip and GPU core count: AB_CHIP and AB_GPU_CORES when set,
// else machdep.cpu.brand_string and the IORegistry's gpu-core-count ("" and 0
// when unavailable, e.g. on a CI runner without a GPU).
void ab_dispatch_host_chip(char *chip, size_t len, int *gpu_cores);

// The chip's short name, as benchmarks/calibration/<slug>/ and the reports
// use it: the chip without "Apple ", runs of non-alphanumerics as one '-',
// then "-<cores>c" when the core count is known ("M2-Max-38c"); "unknown"
// for an empty chip.
void ab_dispatch_chip_slug(const char *chip, int gpu_cores, char *out, size_t len);

// Fills c from the environment variables above and the built-in table for
// this machine's chip, then from AB_DISPATCH_TABLE if set.
void ab_dispatch_config_from_env(ab_dispatch_config_t *c);

// The configuration read from the environment at the first call in this
// process (of this or ab_dispatch_route_gpu()).
const ab_dispatch_config_t *ab_dispatch_process_config(void);

// ab_dispatch_gpu() under ab_dispatch_process_config().
bool ab_dispatch_route_gpu(char routine, char transA, char transB, int M, int N, int K);

// The whole routing of a BLAS-ABI call, as dgemm_ and zgemm_ make it
// (blas_wrapper.c): valid arguments (ab_blas_args_valid), alpha != 0, then
// ab_dispatch_route_gpu(). A call sent to the GPU can still fall back to
// Accelerate (no device, operands beyond the ABMatrix limits).
bool ab_internal_blas_routes_gpu(char routine, char transA, char transB, int M, int N, int K,
                                 int ldA, int ldB, int ldC, bool alpha_nonzero);

// =============================================================================
// AB_SPLIT: the split table
// =============================================================================

// The cut of one call with valid arguments and alpha != 0 under config c:
// false if AB_MODE=cpu, a dimension is <= AB_MIN_GPU_DIM, or no row matches
// (split_on is the caller's to check). Otherwise *out names the first row
// that matches and its axis, L and g (0 for a row with f = 0, or one too
// short to cut: such calls are attributed to the row, not split). alpha_one,
// beta_zero and beta_one are exact (complex parts included); finite: alpha
// and beta are. Pure: reads no environment and no operand.
bool ab_dispatch_split_plan(const ab_dispatch_config_t *c, char routine, char ta, char tb,
                            int M, int N, int K, bool alpha_one, bool beta_zero, bool beta_one,
                            bool finite, ab_split_plan_t *out);

// True if row covers the call by its own windows and the two code limits.
bool ab_split_row_covers(const ab_split_row_t *row, char routine, char ta, char tb,
                         int M, int N, int K, bool alpha_one, bool beta_zero, bool beta_one,
                         bool finite);

// Parses one split table line into *row: 1 for a row, 0 for a blank or
// comment line, -1 if malformed.
int ab_split_parse_row(const char *line, ab_split_row_t *row);

// Replaces c's split rows with those of the file at path, and
// split_table_chip and split_table_gpu_cores with its "# chip:" and
// "# gpu_cores:" (cleared when absent). On failure c is unchanged and err
// says why (with the line number for a malformed line).
bool ab_split_load_table(ab_dispatch_config_t *c, const char *path, char *err, size_t err_len);

// The table of `tables` (ending with a NULL chip) for a chip and GPU core
// count, by the rule of ab_dispatch_select_table; NULL if none. Pure.
const ab_split_table_t *ab_split_select_table(const ab_split_table_t *tables, const char *chip,
                                              int gpu_cores);

// ab_split_select_table() over the built-in set (split_table.h).
const ab_split_table_t *ab_split_builtin_table(const char *chip, int gpu_cores);

// The process configuration's split_table (apple_bottom.h).
const char *ab_split_source(void);

// Records where the latest BLAS-ABI call on this thread computed its result,
// for ab_get_last_dispatch_path() (blas_wrapper.c): the BLAS-2 entry points
// (blas2_abi.c) report through this.
void ab_internal_set_last_path(bool gpu);

#endif // AB_DISPATCH_H

// =============================================================================
// fft.m — double-float complex FFTs on the GPU (apple_bottom_fft.h)
// Copyright (c) 2026 Grant Heileman, Technology Residue. MIT License.
// =============================================================================
//
// A plan is one GPU pass per transformed axis, or two passes (four-step) for
// a rank-1 length longer than a threadgroup can hold. Each pass runs batched
// line FFTs (src/fft/fft_kernel.metal): a threadgroup loads L lines into
// threadgroup memory, runs the Stockham radix passes on them and stores them.
// The first pass reads the caller's FP64 input and converts it on the GPU,
// the last applies the scale and writes FP64; the passes in between use the
// plan's double-float work buffer (packed column-major, 16 bytes a point).
//
// Each pass's kernel is generated for its configuration (line length,
// radices, lanes per line, lines per threadgroup, data kinds, access order)
// and compiled once per process with MTLMathModeSafe.
//
// The passes run over groups of transforms that fit the work buffer. An
// array inside a region from ab_fft_malloc / ab_fft_register is bound in
// place, and then the whole batch is one command buffer. Otherwise the batch
// moves through staging buffers in chunks, two of each so that the copies of
// one chunk overlap the GPU work of the next.
// =============================================================================


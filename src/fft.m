#define ABF_PAGE       16384ul
#define ABF_CPLX       16ul             // bytes per FP64 or double-float complex
#define ABF_MAX_SPAN   0x7FFFFFFFl      // elements a group may span (32-bit kernel indices)
// Threadgroup size targets and staged chunk size, measured on the M2 Max:
// 96 threads / 8 KB was best or within 3.5% for every n^3 grid from 48 to
// 128, and 32 MB chunks best or within 2% for 72^3 and 120^3 batches.
#define ABF_TG_THREADS 96
#define ABF_TG_BYTES   8192
#define ABF_STAGE_MB   32


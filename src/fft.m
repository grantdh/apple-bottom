// Where the elements of a batch are: element (i0, i1, i2) of transform b at
// b*dist + s[0]*i0 + s[1]*i1 + s[2]*i2, in complex elements.
typedef struct { long n[3], s[3], dist; } abf_view;

// Elements from the first to the last element of nb transforms.
static long view_span(const abf_view* v, long nb)
{
    long o = (nb - 1) * v->dist;
    for (int a = 0; a < 3; ++a) o += v->s[a] * (v->n[a] - 1);
    return o + 1;
}

// Same addresses for every element of every transform.
static bool view_equal(const abf_view* a, const abf_view* b, int howmany)
{
    for (int d = 0; d < 3; ++d)
        if (a->n[d] > 1 && a->s[d] != b->s[d]) return false;
    return howmany == 1 || a->dist == b->dist;
}

// No two elements share an address: sorted by stride, each index must step
// past everything the smaller strides span.
static bool view_disjoint(const abf_view* v, int howmany)
{
    long st[4], ex[4];
    int k = 0;
    for (int a = 0; a < 3; ++a)
        if (v->n[a] > 1) { st[k] = v->s[a]; ex[k++] = v->n[a]; }
    if (howmany > 1) { st[k] = v->dist; ex[k++] = howmany; }
    for (int i = 1; i < k; ++i)
        for (int j = i; j > 0 && st[j] < st[j - 1]; --j) {
            long t = st[j]; st[j] = st[j - 1]; st[j - 1] = t;
            t = ex[j]; ex[j] = ex[j - 1]; ex[j - 1] = t;
        }
    for (int i = 1; i < k; ++i)
        if (st[i] < st[i - 1] * ex[i - 1]) return false;
    return true;
}

// A line index of a pass: the other axes and the batch. `twiddle` marks the
// one a four-step twiddle needs as the partner.
typedef struct { long ext, in_s, out_s; int batch, twiddle; } abf_dim;

typedef struct {
    int N, T, L, nrad, radix[ABF_MAX_PASSES];
    int in_f64, out_f64, in_lfast, out_lfast, scale, twout;
    long in_ls, out_ls;
    abf_dim part, q1, q2;
} abf_pass;

@interface ABFPlan : NSObject {
@public
    int rank, n[3], howmany, sign, norm;
    long N;
    abf_view lin, lout;        // the caller's layouts
    int npass;
    abf_pass pass[3];
    id<MTLComputePipelineState> pso[3];
    id<MTLBuffer> tw[3], twf;  // line twiddles per pass; four-step fine table
    float scale_hi, scale_lo;
    long group;                // transforms per GPU group (the work buffer's size)
    long chunk;                // transforms per staged copy chunk
    long run_len;              // output copy-back: contiguous elements per run,
    int run_dims;              // covering this many leading output axes
    id<MTLCommandQueue> queue;
    id<MTLBuffer> work, stageIn[2], stageOut[2];
    os_unfair_lock lock;
    ab_fft_stats stats;
}
@end
@implementation ABFPlan
@end

// Largest divisor of dim in [lmax/2, lmax], else lmax: full threadgroups.
static int pick_lines(int lmax, long dim)
{
    for (int l = lmax; l >= (lmax + 1) / 2; --l)
        if (dim % l == 0) return l;
    return lmax;
}

// Partner: the line index a threadgroup's L lines differ in, the twiddle
// index if there is one, else the one that makes both the loads and the
// stores contiguous.
static void choose_partner(abf_pass* ps, const abf_dim* dims, int nd)
{
    int best = -1, bscore = -1;
    for (int i = 0; i < nd; ++i) {
        const int score = dims[i].twiddle ? 3
                                          : (ps->in_ls == 1 || dims[i].in_s == 1) + (ps->out_ls == 1 || dims[i].out_s == 1);
        if (score > bscore || (score == bscore && dims[i].in_s + dims[i].out_s < dims[best].in_s + dims[best].out_s)) {
            best = i;
            bscore = score;
        }
    }
    const abf_dim one = {1, 0, 0, 0, 0};
    abf_dim rest[2] = {one, one};
    int k = 0;
    for (int i = 0; i < nd; ++i) if (i != best) rest[k++] = dims[i];
    ps->part = best >= 0 ? dims[best] : one;
    ps->q1 = rest[0];
    ps->q2 = rest[1];
    ps->in_lfast = ps->part.ext == 1 || ps->in_ls <= ps->part.in_s;
    ps->out_lfast = ps->part.ext == 1 || ps->out_ls <= ps->part.out_s;
}

// Lines per threadgroup: about ABF_TG_THREADS threads and ABF_TG_BYTES of
// threadgroup memory (one line may use all 32 KB), at most the partner count.
static void set_group(abf_pass* ps, long maxThreads)
{
    long lmax = ABF_TG_THREADS / ps->T;
    if (lmax > ABF_TG_BYTES / (ps->N * (long)ABF_CPLX)) lmax = ABF_TG_BYTES / (ps->N * (long)ABF_CPLX);
    if (lmax > maxThreads / ps->T) lmax = maxThreads / ps->T;
    if (lmax > ps->part.ext) lmax = ps->part.ext;
    if (lmax < 1) lmax = 1;
    ps->L = pick_lines((int)lmax, ps->part.ext);
}

// One pass along logical axis order[k] of sizes m[], for each k: the first
// reads `in`, the last writes `out`, the others the packed work buffer. A
// four-step plan is the same loop over its two line lengths.
static void build_passes(ABFPlan* p, const long m[3], const int* order, int npass, const abf_view* in,
                         const abf_view* work, const abf_view* out, int twiddle)
{
    for (int k = 0; k < npass; ++k) {
        const int a = order[k];
        const abf_view* src = k == 0 ? in : work;
        const abf_view* dst = k == npass - 1 ? out : work;
        abf_pass* ps = &p->pass[k];
        ps->N = (int)m[a];
        ps->nrad = abf_factor(ps->N, ps->radix);
        ps->T = ps->N / abf_max_radix(ps->radix, ps->nrad);
        ps->in_f64 = k == 0;
        ps->out_f64 = k == npass - 1;
        ps->scale = k == npass - 1 && p->norm != AB_FFT_NORM_NONE;
        ps->twout = twiddle && k == 0;
        ps->in_ls = src->s[a];
        ps->out_ls = dst->s[a];
        abf_dim dims[3];
        int nd = 0;
        for (int d = 0; d < 3; ++d)
            if (d != a && m[d] > 1) dims[nd++] = (abf_dim){m[d], src->s[d], dst->s[d], 0, ps->twout};
        if (p->howmany > 1) dims[nd++] = (abf_dim){p->howmany, src->dist, dst->dist, 1, 0};
        choose_partner(ps, dims, nd);
    }
    p->npass = npass;
}

// Output copy-back runs: the leading axes that continue each other in memory.
static void build_runs(ABFPlan* p)
{
    const abf_view* o = &p->lout;
    p->run_len = 1;
    p->run_dims = 0;
    for (int d = 0; d < 3 && (o->n[d] == 1 || o->s[d] == p->run_len); ++d) {
        p->run_len *= o->n[d];
        p->run_dims = d + 1;
    }
}

static NSString* kernel_defines(const abf_pass* ps, int sign)
{
    NSMutableString* s = [NSMutableString stringWithFormat:@"#define ABF_N %du\n#define ABF_T %du\n#define ABF_L %du\n"
                                                           @"#define ABF_PLAN",
                                                           ps->N, ps->T, ps->L];
    for (int i = 0; i < ps->nrad; ++i) [s appendFormat:@" ABF_P(%d)", ps->radix[i]];
    [s appendFormat:@"\n#define ABF_SIGN %d\n#define ABF_IN_F64 %d\n#define ABF_OUT_F64 %d\n", sign, ps->in_f64,
                    ps->out_f64];
    [s appendFormat:@"#define ABF_IN_LFAST %d\n#define ABF_OUT_LFAST %d\n#define ABF_SCALE %d\n#define ABF_TWOUT %d\n",
                    ps->in_lfast, ps->out_lfast, ps->scale, ps->twout];
    return s;
}

static id<MTLBuffer> twiddle_buffer(id<MTLDevice> dev, long n, long count)
{
    id<MTLBuffer> b = [dev newBufferWithLength:(NSUInteger)count * ABF_CPLX options:MTLResourceStorageModeShared];
    if (b) abf_twiddles(n, count, (float*)b.contents);
    return b;
}

// Kernels (threadgroups as large as each compiled pipeline allows; the
// passes compile concurrently) and twiddle tables.
static ABStatus compile_passes(ABFPlan* p, id<MTLDevice> dev)
{
    __block struct { ABStatus st[3]; char err[3][sizeof g_err]; } r = {{AB_OK, AB_OK, AB_OK}, {{0}}};
    dispatch_apply((size_t)p->npass, dispatch_get_global_queue(QOS_CLASS_USER_INITIATED, 0), ^(size_t k) {
        set_group(&p->pass[k], 1024);
        p->pso[k] = pipeline_for(dev, kernel_defines(&p->pass[k], p->sign), &r.st[k]);
        memcpy(r.err[k], g_err, sizeof g_err);   // g_err is per thread
    });
    for (int k = 0; k < p->npass; ++k) {
        abf_pass* ps = &p->pass[k];
        if (!p->pso[k]) {
            memcpy(g_err, r.err[k], sizeof g_err);
            return r.st[k];
        }
        for (int attempt = 0; (long)ps->T * ps->L > (long)p->pso[k].maxTotalThreadsPerThreadgroup; ++attempt) {
            const long maxThreads = (long)p->pso[k].maxTotalThreadsPerThreadgroup;
            if (attempt == 3 || ps->T > maxThreads)
                return fail(AB_ERROR_SHADER_COMPILE, "FFT pass %d: %d lanes per line exceed %ld threads", k, ps->T,
                            maxThreads);
            set_group(ps, maxThreads);
            ABStatus st = AB_OK;
            if (!(p->pso[k] = pipeline_for(dev, kernel_defines(ps, p->sign), &st))) return st;
        }
        for (int j = 0; j < k; ++j)
            if (p->pass[j].N == ps->N) p->tw[k] = p->tw[j];
        if (!p->tw[k]) p->tw[k] = twiddle_buffer(dev, ps->N, ps->N);
        if (!p->tw[k]) return fail(AB_ERROR_ALLOC_FAILED, "twiddle allocation failed");
    }
    // Four-step: W_N^t = W_N2^(t / N1) * W_N^(t mod N1); the coarse table is
    // the second pass's line table, the fine one the first N1 entries of W_N.
    if (p->pass[0].twout && !(p->twf = twiddle_buffer(dev, p->N, p->pass[0].N)))
        return fail(AB_ERROR_ALLOC_FAILED, "twiddle allocation failed");
    return AB_OK;
}

// Largest group of transforms, up to want, whose elements stay within 2^31
// of the group's first in every array a pass indexes.
static long fit_spans(const ABFPlan* p, long want)
{
    const abf_view* v[2] = {&p->lin, &p->lout};
    for (int i = 0; i < 2; ++i)
        if (v[i]->dist > 0 && want > 1)
            want = MIN(want, (ABF_MAX_SPAN - view_span(v[i], 1)) / v[i]->dist + 1);
    if (p->npass > 1) want = MIN(want, ABF_MAX_SPAN / p->N);
    return MAX(1L, want);
}

// GPU groups within the work buffer budget (AB_FFT_WORK_MB); staged chunks
// of about ABF_STAGE_MB, or the whole batch when transforms interleave (a
// chunk's copy is one contiguous span).
static void size_chunks(ABFPlan* p)
{
    const char* env = getenv("AB_FFT_WORK_MB");
    const long mb = env && atol(env) > 0 ? atol(env) : 256;
    p->group = MIN((long)p->howmany, fit_spans(p, (mb << 20) / ((long)ABF_CPLX * p->N)));
    const bool interleaved =
        p->howmany > 1 && (p->lin.dist < view_span(&p->lin, 1) || p->lout.dist < view_span(&p->lout, 1));
    const long per = (long)ABF_CPLX * MAX(p->lin.dist, p->lout.dist);
    const long chunk = interleaved ? p->howmany : MAX(1L, ((long)ABF_STAGE_MB << 20) / MAX(per, 1L));
    const long nch = (p->howmany + chunk - 1) / chunk;
    p->chunk = (p->howmany + nch - 1) / nch;   // equal chunks: no short last one
}

// The caller's layout as a view: stride, embed (NULL: packed) and dist.
static ABStatus make_view(abf_view* v, const int n[3], int rank, const int* embed, long stride, long dist,
                          const char* which)
{
    long s = stride;
    for (int d = 0; d < 3; ++d) {
        const long e = (embed && d < rank - 1) ? embed[d] : n[d];
        if (e < n[d]) return fail(AB_ERROR_INVALID_ARG, "ab_fft_plan_many: %sembed[%d] < n[%d]", which, d, d);
        v->n[d] = n[d];
        v->s[d] = s;
        s *= e;
    }
    v->dist = dist;
    return AB_OK;
}

static ab_fft_plan_t plan_create(int rank, const int* n, int howmany, const int* inembed, long istride, long idist,
                                 const int* onembed, long ostride, long odist, int sign, ab_fft_norm norm,
                                 ABStatus* st)
{
    if (rank < 1 || rank > 3 || !n || howmany < 1 || istride < 1 || ostride < 1 ||
        (howmany > 1 && (idist < 1 || odist < 1)) || (sign != AB_FFT_FORWARD && sign != AB_FFT_BACKWARD) ||
        (norm != AB_FFT_NORM_NONE && norm != AB_FFT_NORM_N && norm != AB_FFT_NORM_SQRT_N)) {
        *st = fail(AB_ERROR_INVALID_ARG, "ab_fft_plan_many: bad rank, howmany, stride, dist, sign or norm");
        return NULL;
    }
    ABFPlan* p = [ABFPlan new];
    p->rank = rank; p->howmany = howmany; p->sign = sign; p->norm = norm;
    p->N = 1;
    int split = ABF_DIRECT, n1 = 0, n2 = 0;
    for (int d = 0; d < 3; ++d) {
        p->n[d] = d < rank ? n[d] : 1;
        if (p->n[d] < 1) { *st = fail(AB_ERROR_INVALID_ARG, "ab_fft_plan_many: n[%d] < 1", d); return NULL; }
        p->N *= p->n[d];
        const int how = abf_line_split(rank, p->n[d], &n1, &n2);
        if (how < 0) {
            *st = fail(AB_ERROR_INVALID_ARG,
                       "ab_fft_plan_many: n[%d] = %d is not supported (factors 2, 3, 5, 7, 11, 13 only; at most "
                       "%d per dimension for rank > 1, %d^2 for rank 1)",
                       d, p->n[d], ABF_MAX_LINE, ABF_MAX_LINE);
            return NULL;
        }
        if (how == ABF_FOUR_STEP) split = how;   // rank 1: n1, n2 are n[0]'s split
    }
    if ((*st = make_view(&p->lin, p->n, rank, inembed, istride, howmany > 1 ? idist : 0, "i")) != AB_OK ||
        (*st = make_view(&p->lout, p->n, rank, onembed, ostride, howmany > 1 ? odist : 0, "o")) != AB_OK)
        return NULL;
    if (!view_disjoint(&p->lout, howmany)) {
        *st = fail(AB_ERROR_INVALID_ARG, "ab_fft_plan_many: output elements overlap");
        return NULL;
    }
    if (view_span(&p->lin, 1) > ABF_MAX_SPAN || view_span(&p->lout, 1) > ABF_MAX_SPAN || p->N > ABF_MAX_SPAN) {
        *st = fail(AB_ERROR_TOO_LARGE, "ab_fft_plan_many: one transform spans more than 2^31 elements");
        return NULL;
    }

    id<MTLDevice> dev = device_get();
    if (!dev) { *st = fail(AB_ERROR_NO_DEVICE, "no Metal device"); return NULL; }
    p->queue = [dev newCommandQueue];
    if (!p->queue) { *st = fail(AB_ERROR_NO_DEVICE, "newCommandQueue failed"); return NULL; }
    p->lock = OS_UNFAIR_LOCK_INIT;

    if (split == ABF_FOUR_STEP) {
        // x[N2*j1 + j2] -> W[k1*N2 + j2] (times W_N^(j2 k1)) -> X[k1 + N1*k2], on
        // logical axes (j2, j1): the first pass along j1, the second along j2.
        const long m[3] = {n2, n1, 1};
        const int order[2] = {1, 0};
        const abf_view in = {{n2, n1, 1}, {istride, istride * n2, 0}, p->lin.dist};
        const abf_view work = {{n2, n1, 1}, {1, n2, 0}, p->N};
        const abf_view out = {{n2, n1, 1}, {ostride * n1, ostride, 0}, p->lout.dist};
        build_passes(p, m, order, 2, &in, &work, &out, 1);
    } else {
        const long m[3] = {p->n[0], p->n[1], p->n[2]};
        int order[3], na = 0;
        for (int a = 0; a < 3; ++a)
            if (m[a] > 1) order[na++] = a;
        if (na == 0) order[na++] = 0;   // N == 1: one pass that converts and scales
        const abf_view work = {{m[0], m[1], m[2]}, {1, m[0], m[0] * m[1]}, p->N};
        build_passes(p, m, order, na, &p->lin, &work, &p->lout, 0);
    }
    if ((*st = compile_passes(p, dev)) != AB_OK) return NULL;
    size_chunks(p);
    abf_hdd_split(abf_scale_hdd(norm, (double)p->N), &p->scale_hi, &p->scale_lo);
    build_runs(p);
    return (ab_fft_plan_t)CFBridgingRetain(p);
}

ab_fft_plan_t ab_fft_plan_many(int rank, const int* n, int howmany,
                               const int* inembed, int istride, int idist,
                               const int* onembed, int ostride, int odist,
                               int sign, ab_fft_norm norm, ABStatus* status)
{
    ABStatus st_dummy;
    ABStatus* st = status ? status : &st_dummy;
    *st = AB_OK;
    g_err[0] = 0;
    @autoreleasepool {
        return plan_create(rank, n, howmany, inembed, istride, idist, onembed, ostride, odist, sign, norm, st);
    }
}

// Packed transforms one after the other: dist = N, computed without overflow.
static ab_fft_plan_t plan_packed(int rank, const int* n, int howmany, int sign, ab_fft_norm norm, ABStatus* status)
{
    ABStatus st_dummy;
    ABStatus* st = status ? status : &st_dummy;
    *st = AB_OK;
    g_err[0] = 0;
    long N = 1;   // bounded: plan_create rejects anything past 2^31 points
    for (int d = 0; d < rank; ++d)
        if (n[d] > 0 && N <= ABF_MAX_SPAN) N *= n[d];
    @autoreleasepool {
        return plan_create(rank, n, howmany, NULL, 1, N, NULL, 1, N, sign, norm, st);
    }
}

ab_fft_plan_t ab_fft_plan_1d(int n0, int howmany, int sign, ab_fft_norm norm, ABStatus* status)
{
    const int n[1] = {n0};
    return plan_packed(1, n, howmany, sign, norm, status);
}

ab_fft_plan_t ab_fft_plan_2d(int n0, int n1, int howmany, int sign, ab_fft_norm norm, ABStatus* status)
{
    const int n[2] = {n0, n1};
    return plan_packed(2, n, howmany, sign, norm, status);
}

ab_fft_plan_t ab_fft_plan_3d(int n0, int n1, int n2, int howmany, int sign, ab_fft_norm norm, ABStatus* status)
{
    const int n[3] = {n0, n1, n2};
    return plan_packed(3, n, howmany, sign, norm, status);
}

void ab_fft_destroy(ab_fft_plan_t plan)
{
    if (plan) @autoreleasepool { CFBridgingRelease(plan); }
}

void ab_fft_get_stats(ab_fft_plan_t plan, ab_fft_stats* stats)
{
    if (!plan || !stats) return;
    ABFPlan* p = (__bridge ABFPlan*)plan;
    os_unfair_lock_lock(&p->lock);
    *stats = p->stats;
    os_unfair_lock_unlock(&p->lock);
}

void ab_fft_describe(ab_fft_plan_t plan, char* buf, size_t len)
{
    if (!buf || !len) return;
    if (!plan) { snprintf(buf, len, "(null plan)"); return; }
    ABFPlan* p = (__bridge ABFPlan*)plan;
    int o = snprintf(buf, len, "rank %d %dx%dx%d howmany %d sign %+d norm %d groups of %ld, staged chunks of %ld:",
                     p->rank, p->n[0], p->n[1], p->n[2], p->howmany, p->sign, p->norm, p->group, p->chunk);
    for (int k = 0; k < p->npass && o > 0 && (size_t)o < len; ++k) {
        const abf_pass* ps = &p->pass[k];
        char rad[64] = "";
        for (int i = 0; i < ps->nrad; ++i)
            snprintf(rad + strlen(rad), sizeof rad - strlen(rad), "%s%d", i ? "x" : "", ps->radix[i]);
        o += snprintf(buf + o, len - (size_t)o, " [N=%d %s T=%d L=%d %s%s->%s%s%s%s]", ps->N, ps->nrad ? rad : "-",
                      ps->T, ps->L, ps->in_f64 ? "f64" : "dd", ps->in_lfast ? "" : "(p)", ps->out_f64 ? "f64" : "dd",
                      ps->out_lfast ? "" : "(p)", ps->scale ? " scale" : "", ps->twout ? " twiddle" : "");
    }
}


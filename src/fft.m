// memcpy, split over up to 8 threads from 2 MB.
static void pcopy(void* dst, const void* src, size_t n)
{
    const size_t slice = (size_t)1 << 20;
    if (n < 2 * slice) { memcpy(dst, src, n); return; }
    size_t k = MIN((size_t)8, n / slice);
    const size_t per = (n + k - 1) / k;
    dispatch_apply(k, dispatch_get_global_queue(QOS_CLASS_USER_INITIATED, 0), ^(size_t i) {
        const size_t o = i * per;
        if (o < n) memcpy((char*)dst + o, (const char*)src + o, MIN(per, n - o));
    });
}

// Copy the output elements of nb transforms from staging to the caller,
// leaving whatever lies between them untouched: the whole span at once when
// the elements fill it (packed or interleaved batches), else run by run.
static void copy_out(const ABFPlan* p, char* dst, const char* src, long nb)
{
    const abf_view* o = &p->lout;
    const long span = view_span(o, nb);
    if (span == nb * p->N) {   // no gaps (the elements' addresses are distinct)
        pcopy(dst, src, (size_t)span * ABF_CPLX);
        return;
    }
    const long runs = p->N / p->run_len, total = nb * runs;
    const size_t rbytes = (size_t)p->run_len * ABF_CPLX;
    const long k = total * (long)rbytes >= (8l << 20) ? 8 : 1;
    const long per = (total + k - 1) / k;
    dispatch_apply((size_t)k, dispatch_get_global_queue(QOS_CLASS_USER_INITIATED, 0), ^(size_t s) {
        const long r1 = MIN(total, (long)(s + 1) * per);
        for (long r = (long)s * per; r < r1; ++r) {
            long off = (r / runs) * o->dist, i = r % runs;
            for (int d = p->run_dims; d < 3; ++d) { off += o->s[d] * (i % o->n[d]); i /= o->n[d]; }
            memcpy(dst + (size_t)off * ABF_CPLX, src + (size_t)off * ABF_CPLX, rbytes);
        }
    });
}

static bool ensure(id<MTLDevice> dev, id<MTLBuffer> __strong* b, size_t bytes)
{
    if (*b && (*b).length >= bytes) return true;
    *b = nil;
    *b = [dev newBufferWithLength:MAX(bytes, ABF_CPLX) options:MTLResourceStorageModeShared];
    return *b != nil;
}

// The passes over nb transforms.
static void encode_group(ABFPlan* p, id<MTLComputeCommandEncoder> e, id<MTLBuffer> inBuf, NSUInteger inOff,
                         id<MTLBuffer> outBuf, NSUInteger outOff, long nb)
{
    for (int k = 0; k < p->npass; ++k) {
        const abf_pass* ps = &p->pass[k];
        abf_dim part = ps->part, q1 = ps->q1, q2 = ps->q2;
        if (part.batch) part.ext = nb;
        if (q1.batch) q1.ext = nb;
        if (q2.batch) q2.ext = nb;
        const abf_params P = {
            .np = (uint32_t)part.ext,
            .in_ls = (uint32_t)ps->in_ls, .in_ps = (uint32_t)part.in_s,
            .in_q1s = (uint32_t)q1.in_s, .in_q2s = (uint32_t)q2.in_s,
            .out_ls = (uint32_t)ps->out_ls, .out_ps = (uint32_t)part.out_s,
            .out_q1s = (uint32_t)q1.out_s, .out_q2s = (uint32_t)q2.out_s,
            .scale_hi = p->scale_hi, .scale_lo = p->scale_lo,
        };
        [e setComputePipelineState:p->pso[k]];
        if (k == 0) [e setBuffer:inBuf offset:inOff atIndex:0];
        else [e setBuffer:p->work offset:0 atIndex:0];
        if (k == p->npass - 1) [e setBuffer:outBuf offset:outOff atIndex:1];
        else [e setBuffer:p->work offset:0 atIndex:1];
        [e setBuffer:p->tw[k] offset:0 atIndex:2];
        [e setBytes:&P length:sizeof P atIndex:3];
        if (ps->twout) {
            [e setBuffer:p->tw[1] offset:0 atIndex:4];
            [e setBuffer:p->twf offset:0 atIndex:5];
        }
        [e dispatchThreadgroups:MTLSizeMake((NSUInteger)((part.ext + ps->L - 1) / ps->L), (NSUInteger)q1.ext,
                                            (NSUInteger)q2.ext)
          threadsPerThreadgroup:MTLSizeMake((NSUInteger)(ps->T * ps->L), 1, 1)];
    }
}

// Wait for the command buffer of chunk c (transforms c*chunk ..) and copy its
// staged output back.
static ABStatus drain(ABFPlan* p, id<MTLCommandBuffer> cb, long c, long chunk, char* out, bool staged)
{
    [cb waitUntilCompleted];
    if (cb.status == MTLCommandBufferStatusError)
        return fail(AB_ERROR_KERNEL_FAILED, "FFT command buffer failed: %s",
                    cb.error ? cb.error.localizedDescription.UTF8String : "unknown error");
    p->stats.gpu_ms += (cb.GPUEndTime - cb.GPUStartTime) * 1e3;
    if (staged) {
        const double t = now_ms();
        const long b0 = c * chunk;
        copy_out(p, out + (size_t)(b0 * p->lout.dist) * ABF_CPLX, p->stageOut[c & 1].contents,
                 MIN(chunk, p->howmany - b0));
        p->stats.copy_out_ms += now_ms() - t;
    }
    return AB_OK;
}

static ABStatus execute_locked(ABFPlan* p, const double* in, double* out)
{
    id<MTLDevice> dev = p->queue.device;
    const size_t inBytes = (size_t)view_span(&p->lin, p->howmany) * ABF_CPLX;
    const size_t outBytes = (size_t)view_span(&p->lout, p->howmany) * ABF_CPLX;
    const char* ib = (const char*)in;
    char* ob = (char*)out;
    if (ib < ob + outBytes && ob < ib + inBytes &&
        !((const void*)in == (void*)out && view_equal(&p->lin, &p->lout, p->howmany)))
        return fail(AB_ERROR_INVALID_ARG, "ab_fft_execute: input and output overlap but are not the same array "
                                          "with the same layout");

    NSUInteger zinOff = 0, zoutOff = 0;
    id<MTLBuffer> zin = region_lookup(in, inBytes, &zinOff);
    id<MTLBuffer> zout = region_lookup(out, outBytes, &zoutOff);
    p->stats.zero_copy_in = zin != nil;
    p->stats.zero_copy_out = zout != nil;

    // Zero copy: one command buffer for the batch. Staged: one per chunk.
    const long chunk = (zin && zout) ? p->howmany : p->chunk;
    const long nch = (p->howmany + chunk - 1) / chunk;
    if (p->npass > 1 && !ensure(dev, &p->work, (size_t)(p->group * p->N) * ABF_CPLX))
        return fail(AB_ERROR_ALLOC_FAILED, "FFT work buffer allocation failed");
    for (int s = 0; s < MIN(2L, nch); ++s)
        if ((!zin && !ensure(dev, &p->stageIn[s], (size_t)view_span(&p->lin, chunk) * ABF_CPLX)) ||
            (!zout && !ensure(dev, &p->stageOut[s], (size_t)view_span(&p->lout, chunk) * ABF_CPLX)))
            return fail(AB_ERROR_ALLOC_FAILED, "FFT staging allocation failed");

    // Chunk c: copy in, commit; then drain chunk c-1, so the copies of one
    // chunk overlap the GPU work of its neighbour.
    id<MTLCommandBuffer> prev = nil;
    ABStatus st = AB_OK;
    for (long c = 0; c < nch && st == AB_OK; ++c) {
        const int slot = (int)(c & 1);
        const long b0 = c * chunk, nb = MIN(chunk, p->howmany - b0);
        if (!zin) {
            const double t = now_ms();
            pcopy(p->stageIn[slot].contents, ib + (size_t)(b0 * p->lin.dist) * ABF_CPLX,
                  (size_t)view_span(&p->lin, nb) * ABF_CPLX);
            p->stats.copy_in_ms += now_ms() - t;
        }
        id<MTLCommandBuffer> cb = [p->queue commandBuffer];
        id<MTLComputeCommandEncoder> e = [cb computeCommandEncoder];
        for (long g0 = 0; g0 < nb; g0 += p->group) {
            const NSUInteger io = (NSUInteger)(g0 * p->lin.dist) * ABF_CPLX, oo = (NSUInteger)(g0 * p->lout.dist) * ABF_CPLX;
            const NSUInteger zio = zinOff + (NSUInteger)(b0 * p->lin.dist) * ABF_CPLX + io;
            const NSUInteger zoo = zoutOff + (NSUInteger)(b0 * p->lout.dist) * ABF_CPLX + oo;
            encode_group(p, e, zin ? zin : p->stageIn[slot], zin ? zio : io, zout ? zout : p->stageOut[slot],
                         zout ? zoo : oo, MIN(p->group, nb - g0));
            p->stats.chunks++;
        }
        [e endEncoding];
        [cb commit];
        if (prev) st = drain(p, prev, c - 1, chunk, ob, !zout);
        prev = cb;
    }
    if (st == AB_OK) st = drain(p, prev, nch - 1, chunk, ob, !zout);
    else [prev waitUntilCompleted];
    return st;
}

ABStatus ab_fft_execute(ab_fft_plan_t plan, const double* in, double* out)
{
    if (!plan || !in || !out) return fail(AB_ERROR_INVALID_ARG, "ab_fft_execute: NULL argument");
    if (g_forked) return fail(AB_ERROR_NO_DEVICE, "ab_fft_execute: plan created before fork()");
    ABFPlan* p = (__bridge ABFPlan*)plan;
    ABStatus st;
    os_unfair_lock_lock(&p->lock);
    @autoreleasepool {
        memset(&p->stats, 0, sizeof p->stats);
        const double t0 = now_ms();
        st = execute_locked(p, in, out);
        p->stats.total_ms = now_ms() - t0;
    }
    os_unfair_lock_unlock(&p->lock);
    return st;
}

static _Thread_local char g_err[256];

const char* ab_fft_last_error(void) { return g_err; }

static ABStatus fail(ABStatus st, const char* fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(g_err, sizeof g_err, fmt, ap);
    va_end(ap);
    return st;
}


@interface ABFRegion : NSObject {
@public
    char* base;          // caller's range
    size_t len;
    id<MTLBuffer> buf;   // covers the page-rounded range
    char* bufBase;
}
@end
@implementation ABFRegion
@end

static os_unfair_lock g_lock = OS_UNFAIR_LOCK_INIT;
static id<MTLDevice> g_dev;
static NSMutableDictionary<NSString*, id<MTLComputePipelineState>>* g_psos;   // by #define block
static NSMutableArray<ABFRegion*>* g_regions;
static NSString* g_msl;
static volatile bool g_forked;

static void abf_atfork_child(void) { g_forked = true; }

// Metal objects do not survive fork(): a child sees no device.
static id<MTLDevice> device_get(void)
{
    os_unfair_lock_lock(&g_lock);
    if (!g_dev && !g_forked) {
        // Creating the device can raise FP exception flags (see ab_init()).
        fenv_t fe;
        feholdexcept(&fe);
        g_dev = MTLCreateSystemDefaultDevice();
        fesetenv(&fe);
        if (g_dev) {
            g_psos = [NSMutableDictionary dictionary];
            g_regions = [NSMutableArray array];
            g_msl = @((const char*)ab_fft_msl);
            pthread_atfork(NULL, NULL, abf_atfork_child);
        }
    }
    id<MTLDevice> d = g_forked ? nil : g_dev;
    os_unfair_lock_unlock(&g_lock);
    return d;
}

// The pass kernel for a #define block, compiled once per process.
static id<MTLComputePipelineState> pipeline_for(id<MTLDevice> dev, NSString* defines, ABStatus* st)
{
    os_unfair_lock_lock(&g_lock);
    id<MTLComputePipelineState> pso = g_psos[defines];
    os_unfair_lock_unlock(&g_lock);
    if (pso) return pso;

    MTLCompileOptions* opts = [[MTLCompileOptions alloc] init];
    // The double-float arithmetic needs IEEE behaviour: no reassociation, no
    // contraction (see the same choice in apple_bottom.m).
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wunguarded-availability"
#pragma clang diagnostic ignored "-Wdeprecated-declarations"
#if defined(__MAC_OS_X_VERSION_MAX_ALLOWED) && __MAC_OS_X_VERSION_MAX_ALLOWED >= 150000
    if ([opts respondsToSelector:@selector(setMathMode:)]) {
        opts.mathMode = MTLMathModeSafe;
    } else
#endif
    {
        opts.fastMathEnabled = NO;
    }
#pragma clang diagnostic pop
    NSError* e = nil;
    fenv_t fe;
    feholdexcept(&fe);
    id<MTLLibrary> lib = [dev newLibraryWithSource:[defines stringByAppendingString:g_msl] options:opts error:&e];
    id<MTLFunction> fn = lib ? [lib newFunctionWithName:@"abf_pass"] : nil;
    if (fn) pso = [dev newComputePipelineStateWithFunction:fn error:&e];
    fesetenv(&fe);
    if (!pso) {
        *st = fail(AB_ERROR_SHADER_COMPILE, "FFT kernel compile failed: %s",
                   e ? e.localizedDescription.UTF8String : "no function");
        return nil;
    }
    os_unfair_lock_lock(&g_lock);
    if (g_psos[defines]) pso = g_psos[defines];
    else g_psos[defines] = pso;
    os_unfair_lock_unlock(&g_lock);
    return pso;
}

// The registered region holding [p, p+len), if any.
static id<MTLBuffer> region_lookup(const void* p, size_t len, NSUInteger* off)
{
    id<MTLBuffer> buf = nil;
    const char* q = (const char*)p;
    os_unfair_lock_lock(&g_lock);
    for (ABFRegion* r in g_regions) {
        if (q >= r->base && q + len <= r->base + r->len) {
            buf = r->buf;
            *off = (NSUInteger)(q - r->bufBase);
            break;
        }
    }
    os_unfair_lock_unlock(&g_lock);
    return buf;
}

static ABStatus region_add(char* base, size_t len, id<MTLBuffer> buf, char* bufBase)
{
    ABStatus st = AB_OK;
    os_unfair_lock_lock(&g_lock);
    for (ABFRegion* r in g_regions)
        if (base < r->base + r->len && r->base < base + len) st = AB_ERROR_INVALID_ARG;
    if (st == AB_OK) {
        ABFRegion* r = [ABFRegion new];
        r->base = base; r->len = len; r->buf = buf; r->bufBase = bufBase;
        [g_regions addObject:r];
    }
    os_unfair_lock_unlock(&g_lock);
    return st == AB_OK ? AB_OK : fail(st, "range overlaps a registered range");
}

static bool region_remove(void* base)
{
    bool found = false;
    os_unfair_lock_lock(&g_lock);
    for (NSUInteger i = 0; i < g_regions.count; ++i) {
        if (g_regions[i]->base == (char*)base) {
            [g_regions removeObjectAtIndex:i];
            found = true;
            break;
        }
    }
    os_unfair_lock_unlock(&g_lock);
    return found;
}

void* ab_fft_malloc(size_t bytes)
{
    @autoreleasepool {
        id<MTLDevice> dev = device_get();
        if (!dev) { fail(AB_ERROR_NO_DEVICE, "no Metal device"); return NULL; }
        size_t len = (bytes + ABF_PAGE - 1) / ABF_PAGE * ABF_PAGE;
        if (!len) len = ABF_PAGE;
        id<MTLBuffer> buf = [dev newBufferWithLength:len options:MTLResourceStorageModeShared];
        if (!buf) { fail(AB_ERROR_ALLOC_FAILED, "ab_fft_malloc(%zu) failed", bytes); return NULL; }
        char* p = (char*)buf.contents;
        if (region_add(p, len, buf, p) != AB_OK) return NULL;
        return p;
    }
}

void ab_fft_free(void* ptr)
{
    if (ptr) @autoreleasepool { region_remove(ptr); }
}

ABStatus ab_fft_register(void* ptr, size_t bytes)
{
    @autoreleasepool {
        if (!ptr || !bytes) return fail(AB_ERROR_INVALID_ARG, "ab_fft_register: NULL pointer or zero length");
        id<MTLDevice> dev = device_get();
        if (!dev) return fail(AB_ERROR_NO_DEVICE, "no Metal device");
        // newBufferWithBytesNoCopy needs whole pages; every page that holds a
        // byte of the range is mapped, so the rounded range is too.
        char* lo = (char*)((uintptr_t)ptr & ~(uintptr_t)(ABF_PAGE - 1));
        char* hi = (char*)(((uintptr_t)ptr + bytes + ABF_PAGE - 1) & ~(uintptr_t)(ABF_PAGE - 1));
        id<MTLBuffer> buf = [dev newBufferWithBytesNoCopy:lo length:(NSUInteger)(hi - lo)
                                                  options:MTLResourceStorageModeShared deallocator:nil];
        if (!buf) return fail(AB_ERROR_ALLOC_FAILED, "ab_fft_register: newBufferWithBytesNoCopy failed");
        return region_add((char*)ptr, bytes, buf, lo);
    }
}

ABStatus ab_fft_unregister(void* ptr)
{
    @autoreleasepool {
        return region_remove(ptr) ? AB_OK : fail(AB_ERROR_INVALID_ARG, "ab_fft_unregister: not a registered range");
    }
}


// A call's TRANS flag as a split row names it: exact, upper-cased, a DGEMM
// 'C' as 'T'; 0 for anything else.
static char split_trans(char routine, char t) {
    switch (t) {
    case 'N': case 'n': return 'N';
    case 'T': case 't': return 'T';
    case 'C': case 'c': return routine == 'd' ? 'T' : 'C';
    default:            return 0;
    }
}

// lo <= v <= hi, with hi 0 for no upper limit.
static bool in_window(double v, double lo, double hi) {
    return v >= lo && (hi <= 0 || v <= hi);
}

bool ab_split_row_covers(const ab_split_row_t *r, char routine, char ta, char tb,
                         int M, int N, int K, bool alpha_one, bool beta_zero, bool beta_one,
                         bool finite) {
    if (r->routine != routine || r->ta != split_trans(routine, ta) ||
        r->tb != split_trans(routine, tb))
        return false;
    if (!in_window(M, r->min_m, r->max_m) || !in_window(N, r->min_n, r->max_n) ||
        !in_window(K, r->min_k, r->max_k) || !in_window((double)M * N, r->min_mn, r->max_mn))
        return false;
    double lo = fmin(fmin(M, N), K), hi = fmax(fmax(M, N), K);   // in double: no overflow
    if (r->ratio > 0 && hi > r->ratio * lo) return false;
    if ((routine == 'z' ? 8.0 : 2.0) * M * N * K / 1e9 < r->min_gf) return false;
    bool scalars = r->scalars == 'u' ? alpha_one && (beta_zero || beta_one)
                 : r->scalars == 'z' ? alpha_one && beta_zero
                 : finite;
    if (!scalars) return false;
    // Limits no table can lift: N- or M-sliced reductions lose the GPU's rate,
    // and the K axis was measured only from K = 7 max(M, N) up.
    if (r->axis == 'K') return (double)K >= 7.0 * fmax(M, N);
    return K <= M;
}

bool ab_dispatch_split_plan(const ab_dispatch_config_t *c, char routine, char ta, char tb,
                            int M, int N, int K, bool alpha_one, bool beta_zero, bool beta_one,
                            bool finite, ab_split_plan_t *out) {
    int MN = M < N ? M : N;
    if (ab_dispatch_mode_route(c, MN < K ? MN : K) == 0) return false;
    for (int i = 0; i < c->split_nrows; i++) {
        const ab_split_row_t *r = &c->split_rows[i];
        if (!ab_split_row_covers(r, routine, ta, tb, M, N, K, alpha_one, beta_zero, beta_one,
                                 finite))
            continue;
        out->row = i;
        out->axis = r->axis;
        out->L = r->axis == 'N' ? N : r->axis == 'M' ? M : K;
        out->g = ab_split_cut(r->axis, out->L, r->share, c->min_dim);
        return true;
    }
    return false;
}

// The text after s's ':', which is cut to end s; NULL if there is none. s is
// the row's own copy (ab_split_parse_row), of any length.
static char *cut_colon(char *s) {
    char *colon = strchr(s, ':');
    if (!colon) return NULL;
    *colon = '\0';
    return colon + 1;
}

// "lo:hi", "lo:" or ":hi" (the colon is required) in ASCII digits: parse_min(),
// which the routing table's rows share, alone would take a sign or a leading
// space. hi 0 or absent is no limit.
static bool parse_range(char *s, int *lo, int *hi) {
    static const char DIGITS[] = "0123456789";
    const char *rest = cut_colon(s);
    *lo = *hi = 0;
    if (!rest || strspn(s, DIGITS) != strlen(s) || strspn(rest, DIGITS) != strlen(rest) ||
        (*s && !parse_min(s, lo)) || (*rest && !parse_min(rest, hi)))
        return false;
    return *hi == 0 || *hi >= *lo;
}

// The C locale, made once: a table reads the same whatever locale the host set.
static locale_t g_c_locale;
static pthread_once_t g_c_locale_once = PTHREAD_ONCE_INIT;
static void make_c_locale(void) { g_c_locale = newlocale(LC_ALL_MASK, "C", NULL); }

// A value of a split row: ASCII digits with an optional point, an optional
// exponent with its sign and an optional leading '+' (scripts/ingest_split.py's
// NUMBER), finite and not negative: no leading '-'.
static bool parse_double(const char *s, double *out) {
    if (!*s || *s == '-' || strspn(s, "0123456789+-.eE") != strlen(s)) return false;
    pthread_once(&g_c_locale_once, make_c_locale);
    char *end;
    errno = 0;
    double v = strtod_l(s, &end, g_c_locale);
    if (errno || *end || end == s || !isfinite(v) || v < 0) return false;
    *out = v;
    return true;
}

static bool parse_drange(char *s, double *lo, double *hi) {
    const char *rest = cut_colon(s);
    *lo = *hi = 0;
    if (!rest || (*s && !parse_double(s, lo)) || (*rest && !parse_double(rest, hi))) return false;
    return *hi == 0 || *hi >= *lo;
}

// The fields of a split row in buf, the line before its comment (changed in
// place): as ab_split_parse_row().
static int parse_split_fields(char *buf, ab_split_row_t *row) {
    static const char *const KEYS[] = {"m", "n", "k", "mn", "ratio", "gf", "scalars", "f"};
    enum { NKEYS = sizeof KEYS / sizeof KEYS[0], KEY_F = NKEYS - 1 };
    char *tok[4 + NKEYS], *save = NULL;
    int n = 0;
    for (char *t = strtok_r(buf, " \t", &save); t; t = strtok_r(NULL, " \t", &save)) {
        if (n == 4 + NKEYS) return -1;
        tok[n++] = t;
    }
    if (n == 0) return 0;
    if (n < 5) return -1;

    ab_split_row_t r;
    memset(&r, 0, sizeof r);
    if (!strcasecmp(tok[0], "dgemm")) r.routine = 'd';
    else if (!strcasecmp(tok[0], "zgemm")) r.routine = 'z';
    else return -1;
    if (strlen(tok[1]) != 1 || strlen(tok[2]) != 1 || strlen(tok[3]) != 1) return -1;
    r.ta = split_trans(r.routine, tok[1][0]);
    r.tb = split_trans(r.routine, tok[2][0]);
    r.axis = (char)toupper((unsigned char)tok[3][0]);
    if (!r.ta || !r.tb || !strchr("NMK", r.axis)) return -1;
    r.scalars = 'a';
    unsigned seen = 0;
    for (int i = 4; i < n; i++) {
        char *eq = strchr(tok[i], '=');
        if (!eq || eq == tok[i]) return -1;
        *eq = '\0';
        char *v = eq + 1;
        int key = -1;
        for (int k = 0; k < NKEYS; k++)
            if (!strcmp(tok[i], KEYS[k])) key = k;
        if (key < 0 || (seen & 1u << key)) return -1;   // unknown, or given twice
        seen |= 1u << key;
        bool ok;
        switch (key) {
        case 0: ok = parse_range(v, &r.min_m, &r.max_m); break;
        case 1: ok = parse_range(v, &r.min_n, &r.max_n); break;
        case 2: ok = parse_range(v, &r.min_k, &r.max_k); break;
        case 3: ok = parse_drange(v, &r.min_mn, &r.max_mn); break;
        case 4: ok = parse_double(v, &r.ratio) && r.ratio >= 1.0; break;
        case 5: ok = parse_double(v, &r.min_gf); break;
        case 6: ok = strlen(v) == 1 && strchr("uza", v[0]); r.scalars = v[0]; break;
        default: ok = parse_double(v, &r.share) && r.share <= 1.0; break;
        }
        if (!ok) return -1;
    }
    if (!(seen & 1u << KEY_F)) return -1;                // a share is required
    *row = r;
    return 1;
}

int ab_split_parse_row(const char *line, ab_split_row_t *row) {
    size_t n = strcspn(line, "#\r\n");                   // the row, whatever its length
    char *buf = malloc(n + 1);
    if (!buf) return -1;
    memcpy(buf, line, n);
    buf[n] = '\0';
    int got = parse_split_fields(buf, row);
    free(buf);
    return got;
}

// Why a split table's line (n bytes as read, its "\n" included) is refused
// whatever it says, or NULL: a '\r' other than one that ends it, a NUL, or an
// ASCII control character other than a tab, comments included
// (scripts/ingest_split.py refuses the same).
static const char *split_line_why(const char *line, size_t n) {
    if (n && line[n - 1] == '\n') n--;
    if (n && line[n - 1] == '\r') n--;
    if (memchr(line, '\r', n)) return "a carriage return inside the line";
    if (memchr(line, '\0', n)) return "a NUL byte";
    for (size_t i = 0; i < n; i++) {
        unsigned char ch = (unsigned char)line[i];
        if ((ch < 0x20 && ch != '\t') || ch == 0x7f) return "a control character";
    }
    return NULL;
}

bool ab_split_load_table(ab_dispatch_config_t *c, const char *path, char *err, size_t err_len) {
    FILE *f = fopen(path, "r");
    if (!f) {
        snprintf(err, err_len, "%s", strerror(errno));
        return false;
    }
    ab_split_row_t rows[AB_SPLIT_MAX_ROWS];
    char *line = NULL, chip[AB_DISPATCH_CHIP_LEN] = "", key[32], value[AB_DISPATCH_CHIP_LEN];
    size_t cap = 0;
    ssize_t len;
    int nrows = 0, lineno = 0, cores = 0;
    const char *why = NULL;
    while (!why && (len = getline(&line, &cap, f)) >= 0) {   // lines of any length
        lineno++;
        if ((why = split_line_why(line, (size_t)len))) break;
        if (ab_dispatch_parse_header(line, key, sizeof key, value, sizeof value)) {
            if (!strcmp(key, "chip")) snprintf(chip, sizeof chip, "%s", value);
            else if (!strcmp(key, "gpu_cores")) cores = atoi(value) > 0 ? atoi(value) : 0;
            continue;
        }
        ab_split_row_t r;
        int got = ab_split_parse_row(line, &r);
        if (got < 0)
            why = "expected '<dgemm|zgemm> <N|T|C> <N|T|C> <N|M|K> [m=lo:hi] [n=lo:hi] [k=lo:hi] "
                  "[mn=lo:hi] [ratio=r] [gf=g] [scalars=u|z|a] f=<share>'";
        else if (got && nrows == AB_SPLIT_MAX_ROWS)
            why = "too many rows";
        else if (got)
            rows[nrows++] = r;
    }
    if (!why && ferror(f)) why = "read error";
    free(line);
    fclose(f);
    if (why) {
        snprintf(err, err_len, "line %d: %s", lineno, why);
        return false;
    }
    memcpy(c->split_rows, rows, (size_t)nrows * sizeof rows[0]);
    c->split_nrows = nrows;
    snprintf(c->split_table_chip, sizeof c->split_table_chip, "%s", chip);
    c->split_table_gpu_cores = cores;
    return true;
}


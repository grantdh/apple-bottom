// "38 GPU cores", or "an unstated GPU core count" for 0, for the notes below.
static const char *cores_text(int n, char *buf, size_t len) {
    if (n > 0) snprintf(buf, len, "%d GPU cores", n);
    else snprintf(buf, len, "an unstated GPU core count");
    return buf;
}

static uint64_t env_flops(const char *name) {
    const char *s = getenv(name);
    return s && *s ? strtoull(s, NULL, 10) : 0;
}

// A dimension from the environment: fallback if unset, empty or negative.
static int env_dim(const char *name, int fallback) {
    const char *s = getenv(name);
    int v = s && *s ? atoi(s) : fallback;
    return v < 0 ? fallback : v;
}

// AB_SPLIT and AB_SPLIT_TABLE: off leaves no rows. On, the built-in split
// table for this chip, replaced by the file AB_SPLIT_TABLE names (one that
// cannot be read or parsed keeps the built-in, with a note); a chip with
// neither splits nothing, with a note.
static void split_config_from_env(ab_dispatch_config_t *c) {
    const char *on = getenv("AB_SPLIT");
    c->split_on = on && *on && *on != '0';
    if (!c->split_on) {
        snprintf(c->split_table, sizeof c->split_table, "off");
        return;
    }
    const ab_split_table_t *t = ab_split_builtin_table(c->chip, c->gpu_cores);
    if (t) {
        for (const ab_split_row_t *r = t->rows; r->routine && c->split_nrows < AB_SPLIT_MAX_ROWS; r++)
            c->split_rows[c->split_nrows++] = *r;
        snprintf(c->split_table_chip, sizeof c->split_table_chip, "%s", t->chip);
        c->split_table_gpu_cores = t->gpu_cores;
        char slug[AB_DISPATCH_CHIP_LEN];
        ab_dispatch_chip_slug(t->chip, t->gpu_cores, slug, sizeof slug);
        snprintf(c->split_table, sizeof c->split_table, "builtin:%s@%s", slug, t->library);
    } else {
        snprintf(c->split_table, sizeof c->split_table, "none:%s",
                 c->chip[0] ? "uncalibrated-chip" : "unknown-chip");
    }

    const char *table = getenv("AB_SPLIT_TABLE");
    char err[200];
    bool named = table && *table;
    if (named && strlen(table) > AB_SPLIT_PATH_MAX) {
        // The label names the file in every report: one cut short would not.
        fprintf(stderr, "apple-bottom: AB_SPLIT_TABLE=%s: path longer than %zu bytes; keeping %s\n", table,
                (size_t)AB_SPLIT_PATH_MAX, c->split_table);
    } else if (named && !ab_split_load_table(c, table, err, sizeof err)) {
        fprintf(stderr, "apple-bottom: AB_SPLIT_TABLE=%s: %s; keeping %s\n", table, err, c->split_table);
    } else if (named) {
        snprintf(c->split_table, sizeof c->split_table, "file:%s", table);
        bool other_chip = c->split_table_chip[0] && c->chip[0] && strcasecmp(c->split_table_chip, c->chip);
        bool other_cores = c->split_table_gpu_cores && c->gpu_cores &&
                           c->split_table_gpu_cores != c->gpu_cores;
        if (other_chip || other_cores) {
            char tc[40], hc[40];
            fprintf(stderr, "apple-bottom: AB_SPLIT_TABLE=%s was measured on %s with %s; this "
                            "machine is %s with %s; using it anyway\n",
                    table, c->split_table_chip, cores_text(c->split_table_gpu_cores, tc, sizeof tc),
                    c->chip[0] ? c->chip : "an unknown chip", cores_text(c->gpu_cores, hc, sizeof hc));
        }
    }
    if (!strncmp(c->split_table, "none:", 5))
        fprintf(stderr, "apple-bottom: AB_SPLIT=1, but %s has no split table and %s; nothing is split\n",
                c->chip[0] ? c->chip : "this chip (unknown)",
                named ? "the AB_SPLIT_TABLE file could not be used" : "AB_SPLIT_TABLE names none");
}

void ab_dispatch_config_from_env(ab_dispatch_config_t *c) {
    memset(c, 0, sizeof *c);
    const char *mode = getenv("AB_MODE");
    c->mode = mode && (mode[0] == 'c' || mode[0] == 'C') ? AB_DISPATCH_CPU
            : mode && (mode[0] == 'g' || mode[0] == 'G') ? AB_DISPATCH_GPU
            : AB_DISPATCH_AUTO;

    c->min_dim = env_dim("AB_MIN_GPU_DIM", AB_DISPATCH_DEFAULT_MIN_DIM);
    c->blas2_min_dim = env_dim("AB_BLAS2_MIN_DIM", AB_DISPATCH_DEFAULT_BLAS2_MIN_DIM);

    c->crossover_flops = env_flops("AB_CROSSOVER_FLOPS");
    c->crossover_flops_real = env_flops("AB_CROSSOVER_FLOPS_REAL");

    // The built-in table for this chip, if it was calibrated.
    ab_dispatch_host_chip(c->chip, sizeof c->chip, &c->gpu_cores);
    const ab_dispatch_table_t *t = ab_dispatch_builtin_table(c->chip, c->gpu_cores);
    if (t) {
        for (const ab_dispatch_row_t *r = t->rows; r->routine && c->nrows < AB_DISPATCH_MAX_ROWS; r++)
            c->rows[c->nrows++] = *r;
        snprintf(c->table_chip, sizeof c->table_chip, "%s", t->chip);
        c->table_gpu_cores = t->gpu_cores;
        char slug[AB_DISPATCH_CHIP_LEN];
        ab_dispatch_chip_slug(t->chip, t->gpu_cores, slug, sizeof slug);
        snprintf(c->table, sizeof c->table, "builtin:%s", slug);
    } else {
        snprintf(c->table, sizeof c->table, "none:%s", c->chip[0] ? "uncalibrated-chip" : "unknown-chip");
    }

    const char *table = getenv("AB_DISPATCH_TABLE");
    char err[160];
    if (table && *table) {
        if (!ab_dispatch_load_table(c, table, err, sizeof err)) {
            fprintf(stderr, "apple-bottom: AB_DISPATCH_TABLE=%s: %s; keeping %s\n", table, err, c->table);
        } else {
            snprintf(c->table, sizeof c->table, "file:%s", table);
            bool other_chip = c->table_chip[0] && c->chip[0] && strcasecmp(c->table_chip, c->chip);
            bool other_cores = c->table_gpu_cores && c->gpu_cores && c->table_gpu_cores != c->gpu_cores;
            if (other_chip || other_cores) {
                char tc[40], hc[40];
                fprintf(stderr, "apple-bottom: AB_DISPATCH_TABLE=%s was calibrated on %s with %s; this machine "
                                "is %s with %s; using it anyway\n",
                        table, c->table_chip, cores_text(c->table_gpu_cores, tc, sizeof tc),
                        c->chip[0] ? c->chip : "an unknown chip", cores_text(c->gpu_cores, hc, sizeof hc));
            }
        }
    }
    split_config_from_env(c);
}

static ab_dispatch_config_t g_config;
static pthread_once_t g_config_once = PTHREAD_ONCE_INIT;

static void load_config(void) { ab_dispatch_config_from_env(&g_config); }

const ab_dispatch_config_t *ab_dispatch_process_config(void) {
    pthread_once(&g_config_once, load_config);
    return &g_config;
}

bool ab_dispatch_route_gpu(char routine, char transA, char transB, int M, int N, int K) {
    return ab_dispatch_gpu(ab_dispatch_process_config(), routine, transA, transB, M, N, K);
}


static bool parse_trans(const char *tok, char *out) {
    if (strlen(tok) != 1 || !strchr("NTCntc", tok[0])) return false;
    *out = trans_class(tok[0]);
    return true;
}

static bool parse_min(const char *tok, int *out) {
    char *end;
    errno = 0;
    long v = strtol(tok, &end, 10);
    if (errno || *end || end == tok || v < 0 || v > INT_MAX) return false;
    *out = (int)v;
    return true;
}

int ab_dispatch_parse_row(const char *line, ab_dispatch_row_t *row) {
    char buf[256], *tok[6], *save = NULL;
    int n = 0;
    snprintf(buf, sizeof buf, "%s", line);
    buf[strcspn(buf, "#\r\n")] = '\0';
    for (char *t = strtok_r(buf, " \t", &save); t; t = strtok_r(NULL, " \t", &save)) {
        if (n == 6) return -1;
        tok[n++] = t;
    }
    if (n == 0) return 0;
    if (n != 6) return -1;

    ab_dispatch_row_t r;
    if (!strcasecmp(tok[0], "dgemm")) r.routine = 'd';
    else if (!strcasecmp(tok[0], "zgemm")) r.routine = 'z';
    else return -1;
    if (!parse_trans(tok[1], &r.ta) || !parse_trans(tok[2], &r.tb) ||
        !parse_min(tok[3], &r.m) || !parse_min(tok[4], &r.n) || !parse_min(tok[5], &r.k))
        return -1;
    *row = r;
    return 1;
}

// Copies s without leading or trailing blanks into out.
static void trimmed(const char *s, size_t n, char *out, size_t len) {
    while (n && isspace((unsigned char)*s)) { s++; n--; }
    while (n && isspace((unsigned char)s[n - 1])) n--;
    if (n >= len) n = len - 1;
    memcpy(out, s, n);
    out[n] = '\0';
}

int ab_dispatch_parse_header(const char *line, char *key, size_t key_len,
                             char *value, size_t value_len) {
    const char *p = line + strspn(line, " \t");
    if (*p != '#') return 0;
    p++;
    p += strspn(p, " \t");
    const char *colon = strchr(p, ':');
    if (!colon || colon == p) return 0;
    // A key is one lowercase word (letters, digits, '_'); "# Machine:  ..."
    // and the other prose lines of a table header are not keys.
    for (const char *q = p; q < colon; q++)
        if (!(islower((unsigned char)*q) || isdigit((unsigned char)*q) || *q == '_')) return 0;
    trimmed(p, (size_t)(colon - p), key, key_len);
    trimmed(colon + 1, strcspn(colon + 1, "#\r\n"), value, value_len);   // a trailing "# note" is not the value
    return 1;
}

bool ab_dispatch_load_table(ab_dispatch_config_t *c, const char *path,
                            char *err, size_t err_len) {
    FILE *f = fopen(path, "r");
    if (!f) {
        snprintf(err, err_len, "%s", strerror(errno));
        return false;
    }
    ab_dispatch_row_t rows[AB_DISPATCH_MAX_ROWS];
    char line[256], chip[AB_DISPATCH_CHIP_LEN] = "", key[32], value[AB_DISPATCH_CHIP_LEN];
    int nrows = 0, lineno = 0, cores = 0;
    const char *why = NULL;
    while (!why && fgets(line, sizeof line, f)) {
        lineno++;
        // A line longer than the buffer is allowed only as a comment.
        bool whole = strchr(line, '\n') || feof(f);
        bool comment = line[strspn(line, " \t")] == '#';
        for (int ch = 0; !whole && ch != '\n' && ch != EOF; ) ch = fgetc(f);
        if (comment && ab_dispatch_parse_header(line, key, sizeof key, value, sizeof value)) {
            if (!strcmp(key, "chip")) snprintf(chip, sizeof chip, "%s", value);
            else if (!strcmp(key, "gpu_cores")) cores = atoi(value) > 0 ? atoi(value) : 0;
            continue;
        }
        ab_dispatch_row_t r;
        int got = whole || comment ? ab_dispatch_parse_row(line, &r) : -1;
        if (got < 0)
            why = "expected '<dgemm|zgemm> <N|T|C> <N|T|C> <min_M> <min_N> <min_K>'";
        else if (got && nrows == AB_DISPATCH_MAX_ROWS)
            why = "too many rows";
        else if (got)
            rows[nrows++] = r;
    }
    if (!why && ferror(f)) why = "read error";
    fclose(f);
    if (why) {
        snprintf(err, err_len, "line %d: %s", lineno, why);
        return false;
    }
    memcpy(c->rows, rows, (size_t)nrows * sizeof rows[0]);
    c->nrows = nrows;
    snprintf(c->table_chip, sizeof c->table_chip, "%s", chip);
    c->table_gpu_cores = cores;
    return true;
}


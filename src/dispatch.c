// The rule of ab_dispatch_select_table, over an array of either kind of
// table (ab_dispatch_table_t, ab_split_table_t), stride bytes apart, ending
// with a NULL chip: both start with the chip and its core count.
typedef struct { const char *chip; int gpu_cores; } table_id_t;
_Static_assert(offsetof(ab_dispatch_table_t, chip) == offsetof(table_id_t, chip) &&
               offsetof(ab_dispatch_table_t, gpu_cores) == offsetof(table_id_t, gpu_cores) &&
               offsetof(ab_split_table_t, chip) == offsetof(table_id_t, chip) &&
               offsetof(ab_split_table_t, gpu_cores) == offsetof(table_id_t, gpu_cores),
               "tables start with chip and gpu_cores");

static const void *select_table(const void *tables, size_t stride, const char *chip,
                                int gpu_cores) {
    if (!chip || !*chip) return NULL;
    const table_id_t *exact = NULL, *any_cores = NULL, *only = NULL;
    int same_chip = 0;
    for (const char *p = tables; ((const table_id_t *)p)->chip; p += stride) {
        const table_id_t *t = (const table_id_t *)p;
        if (strcasecmp(t->chip, chip)) continue;
        same_chip++;
        only = t;
        if (gpu_cores > 0 && t->gpu_cores == gpu_cores) exact = t;
        if (t->gpu_cores == 0 && !any_cores) any_cores = t;
    }
    if (exact) return exact;
    if (any_cores) return any_cores;
    if (gpu_cores <= 0 && same_chip == 1) return only;
    return NULL;
}

const ab_dispatch_table_t *ab_dispatch_select_table(const ab_dispatch_table_t *tables,
                                                    const char *chip, int gpu_cores) {
    return select_table(tables, sizeof *tables, chip, gpu_cores);
}

const ab_dispatch_table_t *ab_dispatch_builtin_table(const char *chip, int gpu_cores) {
    return ab_dispatch_select_table(AB_DISPATCH_BUILTIN_TABLES, chip, gpu_cores);
}

// gpu-core-count of the first AGXAccelerator entry, as `ioreg -rc
// AGXAccelerator -d1` lists it; 0 when there is none (a CI runner without a
// GPU) or the property is missing.
static int ioregistry_gpu_cores(void) {
    io_iterator_t it = IO_OBJECT_NULL;
    if (IOServiceGetMatchingServices(kIOMainPortDefault, IOServiceMatching("AGXAccelerator"), &it) !=
        KERN_SUCCESS)
        return 0;
    int cores = 0;
    for (io_object_t s; !cores && (s = IOIteratorNext(it)); IOObjectRelease(s)) {
        CFTypeRef v = IORegistryEntryCreateCFProperty(s, CFSTR("gpu-core-count"), kCFAllocatorDefault, 0);
        if (!v) continue;
        if (CFGetTypeID(v) == CFNumberGetTypeID() && !CFNumberGetValue(v, kCFNumberIntType, &cores))
            cores = 0;
        CFRelease(v);
    }
    IOObjectRelease(it);
    return cores > 0 ? cores : 0;
}

void ab_dispatch_chip_slug(const char *chip, int gpu_cores, char *out, size_t len) {
    const char *s = chip ? chip : "";
    if (!strncasecmp(s, "Apple", 5)) s += 5;
    size_t n = 0;
    bool dash = true;                       // no leading dash
    for (; *s && n + 1 < len; s++) {
        if (isalnum((unsigned char)*s)) { out[n++] = *s; dash = false; }
        else if (!dash) { out[n++] = '-'; dash = true; }
    }
    while (n && out[n - 1] == '-') n--;
    out[n] = '\0';
    if (!n) snprintf(out, len, "unknown");
    else if (gpu_cores > 0) snprintf(out + n, len - n, "-%dc", gpu_cores);
}

void ab_dispatch_host_chip(char *chip, size_t len, int *gpu_cores) {
    const char *env = getenv("AB_CHIP");
    if (env && *env) {
        trimmed(env, strlen(env), chip, len);
    } else {
        size_t n = len;
        if (sysctlbyname("machdep.cpu.brand_string", chip, &n, NULL, 0) != 0 || n == 0) chip[0] = '\0';
        chip[len - 1] = '\0';
    }
    env = getenv("AB_GPU_CORES");
    if (env && *env) {
        int v = atoi(env);
        *gpu_cores = v > 0 ? v : 0;
    } else {
        *gpu_cores = ioregistry_gpu_cores();
    }
}

